using System.Text.Json;
using System.Text.Json.Nodes;
using System.Text.Json.Serialization;

namespace TurnRoi.Core.Apply;

/// <summary>
/// One file TurnROI wants to create, change or delete. <see cref="Before"/> is null when the file doesn't exist yet;
/// <see cref="After"/> is null when the file should be deleted.
/// </summary>
public sealed record FileChange(string Path, string? Before, string? After, string Description)
{
    public bool IsCreate => Before is null;
    public bool IsDelete => After is null;
}

/// <summary>What to write: rules, skill, guardrail settings and/or hooks, for one or more agents.</summary>
public sealed record ApplyOptions(
    IReadOnlyList<TargetAgent> Agents,
    bool Rules = true,
    bool Skill = true,
    bool Hooks = true,
    bool Config = true,
    string HookCommand = "turnroi",
    bool SharedClaudeSettings = false);

/// <summary>
/// Turns <see cref="RepoGuidance"/> into concrete file changes for each agent, always editing only what TurnROI owns:
/// a marked block inside shared files (CLAUDE.md, copilot-instructions.md), its own hook entries inside settings files,
/// and whole files it generated itself. Files someone else wrote are never overwritten.
/// </summary>
public static class ApplyPlanner
{
    public const string BlockStart = "<!-- turnroi:begin (generated by TurnROI; edits inside this block are replaced) -->";
    public const string BlockEnd = "<!-- turnroi:end -->";
    private const string OwnershipMark = "TurnROI";

    public static (IReadOnlyList<FileChange> Changes, IReadOnlyList<string> Skipped) Plan(
        string projectDir, RepoGuidance? guidance, ApplyOptions options, Func<string, string?>? read = null)
    {
        read ??= p => File.Exists(p) ? File.ReadAllText(p) : null;
        var changes = new List<FileChange>();
        var skipped = new List<string>();

        void Add(string relative, Func<string?, string?> transform, string description)
        {
            var path = System.IO.Path.Combine(projectDir, relative);
            var before = read(path);
            string? after;
            try { after = transform(before); }
            catch (InvalidOperationException ex) { skipped.Add($"{relative}: {ex.Message}"); return; }
            if (after is null) { skipped.Add($"{relative}: exists and wasn't created by TurnROI, left unchanged"); return; }
            if (after != before) changes.Add(new FileChange(path, before, after, description));
        }

        foreach (var agent in options.Agents.Distinct())
        {
            if (options.Rules && guidance is not null && guidance.Rules.Count + (guidance.HasSkillContent ? 1 : 0) > 0)
            {
                switch (agent)
                {
                    case TargetAgent.Claude:
                        Add("CLAUDE.md", b => UpsertBlock(b, guidance.RulesMarkdown()), "always-on rules (managed block)");
                        break;
                    case TargetAgent.Copilot:
                        Add(".github/copilot-instructions.md", b => UpsertBlock(b, guidance.RulesMarkdown()), "always-on rules (managed block)");
                        break;
                    case TargetAgent.Cursor:
                        Add(".cursor/rules/turnroi.mdc", b => OwnedFile(b, CursorRule(guidance)), "always-on rule");
                        break;
                }
            }

            if (options.Skill && guidance is { HasSkillContent: true })
            {
                var folder = agent switch
                {
                    TargetAgent.Claude => ".claude/skills",
                    TargetAgent.Cursor => ".cursor/skills",
                    _ => ".github/skills",
                };
                Add($"{folder}/{RepoGuidance.SkillName}/SKILL.md", b => OwnedFile(b, guidance.SkillMarkdown()), "skill");
            }

            if (options.Hooks)
            {
                switch (agent)
                {
                    case TargetAgent.Claude:
                        Add(options.SharedClaudeSettings ? ".claude/settings.json" : ".claude/settings.local.json",
                            b => HookConfig.MergeClaude(b, options.HookCommand), "hooks");
                        break;
                    case TargetAgent.Cursor:
                        Add(".cursor/hooks.json", b => HookConfig.MergeCursor(b, options.HookCommand), "hooks");
                        break;
                    case TargetAgent.Copilot:
                        Add(".github/hooks/turnroi.json", b => OwnedFile(b, HookConfig.CopilotFile(options.HookCommand)), "hooks");
                        break;
                }
            }
        }

        if (options.Config && guidance is not null)
        {
            Add(Guardrails.GuardrailConfig.FileName,
                b => b is null || b.Contains("\"rereadGuard\"", StringComparison.Ordinal) && guidance.Guardrails.TurnBudgetTokens is not null
                    ? MergeConfig(b, guidance.Guardrails)
                    : b,
                "guardrail settings");
        }

        return (changes, skipped);
    }

    /// <summary>Plan removal of TurnROI's hook entries for the given agents; other hooks and settings stay.</summary>
    public static IReadOnlyList<FileChange> PlanHookRemoval(string projectDir, IReadOnlyList<TargetAgent> agents, Func<string, string?>? read = null)
    {
        read ??= p => File.Exists(p) ? File.ReadAllText(p) : null;
        var changes = new List<FileChange>();
        void Remove(string relative, Func<string, (bool Changed, string? After)> transform, string description)
        {
            var path = System.IO.Path.Combine(projectDir, relative);
            if (read(path) is not { } before) return;
            var (changed, after) = transform(before);
            if (changed) changes.Add(new FileChange(path, before, after, description));
        }

        foreach (var agent in agents.Distinct())
        {
            switch (agent)
            {
                case TargetAgent.Claude:
                    Remove(".claude/settings.local.json", b => Changed(HookConfig.RemoveClaude(b)), "remove hooks");
                    Remove(".claude/settings.json", b => Changed(HookConfig.RemoveClaude(b)), "remove hooks");
                    break;
                case TargetAgent.Cursor:
                    Remove(".cursor/hooks.json", b => Changed(HookConfig.RemoveCursor(b)), "remove hooks");
                    break;
                case TargetAgent.Copilot:
                    Remove(".github/hooks/turnroi.json", b => (b.Contains(OwnershipMark, StringComparison.OrdinalIgnoreCase), null), "delete hooks file");
                    break;
            }
        }
        return changes;

        static (bool, string?) Changed(string? after) => (after is not null, after);
    }

    /// <summary>Inserts or replaces the TurnROI block, leaving the rest of the file untouched.</summary>
    public static string UpsertBlock(string? existing, string content)
    {
        var block = $"{BlockStart}\n{content.TrimEnd()}\n{BlockEnd}\n";
        if (string.IsNullOrEmpty(existing)) return block;

        var start = existing.IndexOf(BlockStart, StringComparison.Ordinal);
        var end = existing.IndexOf(BlockEnd, StringComparison.Ordinal);
        if (start >= 0 && end > start)
        {
            var after = end + BlockEnd.Length;
            if (after < existing.Length && existing[after] == '\n') after++;
            return existing[..start] + block + existing[after..];
        }
        if (start >= 0 || end >= 0)
            throw new InvalidOperationException("has an incomplete TurnROI block; fix or remove it first");

        var separator = existing.EndsWith("\n\n", StringComparison.Ordinal) ? "" : existing.EndsWith('\n') ? "\n" : "\n\n";
        return existing + separator + block;
    }

    /// <summary>Removes the TurnROI block, if any.</summary>
    public static string RemoveBlock(string existing)
    {
        var start = existing.IndexOf(BlockStart, StringComparison.Ordinal);
        var end = existing.IndexOf(BlockEnd, StringComparison.Ordinal);
        if (start < 0 || end < start) return existing;
        var after = end + BlockEnd.Length;
        if (after < existing.Length && existing[after] == '\n') after++;
        return (existing[..start].TrimEnd('\n') + "\n" + existing[after..]).TrimStart('\n');
    }

    /// <summary>A whole file TurnROI generates: written when absent or when it is TurnROI's own; null otherwise.</summary>
    private static string? OwnedFile(string? existing, string content) =>
        existing is null || existing.Contains(OwnershipMark, StringComparison.OrdinalIgnoreCase) ? content : null;

    private static string CursorRule(RepoGuidance g) =>
        "---\n" +
        "description: Token efficiency rules generated by TurnROI from this repository's agent sessions\n" +
        "alwaysApply: true\n" +
        "---\n\n" +
        g.RulesMarkdown();

    private static string MergeConfig(string? existing, Guardrails.GuardrailConfig tuned)
    {
        var config = existing is null ? new Guardrails.GuardrailConfig() : ParseConfig(existing);
        if (tuned.TurnBudgetTokens is not null) config.TurnBudgetTokens = tuned.TurnBudgetTokens;
        return config.ToJson() + "\n";
    }

    private static Guardrails.GuardrailConfig ParseConfig(string json)
    {
        try { return JsonSerializer.Deserialize(json, ApplyJsonContext.Default.GuardrailConfig) ?? new(); }
        catch (JsonException) { throw new InvalidOperationException("is not valid JSON; fix it first"); }
    }
}

/// <summary>Reads and writes each agent's hook configuration, touching only TurnROI's own entries.</summary>
public static class HookConfig
{
    private static readonly JsonSerializerOptions Indented = new() { WriteIndented = true };

    public static bool IsOurs(JsonNode? entry) =>
        entry?.ToJsonString() is { } json &&
        json.Contains("turnroi", StringComparison.OrdinalIgnoreCase) &&
        (json.Contains(" hook pre-tool-use", StringComparison.Ordinal) || json.Contains(" hook post-tool-use", StringComparison.Ordinal));

    /// <summary>Claude Code: .claude/settings(.local).json, {"hooks": {"PreToolUse": [{matcher, hooks: [...]}]}}.</summary>
    public static string MergeClaude(string? existing, string command)
    {
        var settings = Parse(existing);
        var hooks = settings["hooks"] as JsonObject ?? new JsonObject();
        settings["hooks"] = hooks;
        foreach (var (evt, sub) in new[] { ("PreToolUse", "pre-tool-use"), ("PostToolUse", "post-tool-use") })
        {
            var list = Replace(hooks, evt);
            list.Add(new JsonObject
            {
                ["matcher"] = "*",
                ["hooks"] = new JsonArray(new JsonObject { ["type"] = "command", ["command"] = $"{command} hook {sub}", ["timeout"] = 10 }),
            });
        }
        return settings.ToJsonString(Indented) + "\n";
    }

    public static string? RemoveClaude(string existing) => Remove(existing, "hooks");

    /// <summary>Cursor: .cursor/hooks.json, {"version": 1, "hooks": {"preToolUse": [{"command": "..."}]}}.</summary>
    public static string MergeCursor(string? existing, string command)
    {
        var root = Parse(existing);
        root["version"] ??= 1;
        var hooks = root["hooks"] as JsonObject ?? new JsonObject();
        root["hooks"] = hooks;
        foreach (var (evt, sub) in new[] { ("preToolUse", "pre-tool-use"), ("postToolUse", "post-tool-use") })
            Replace(hooks, evt).Add(new JsonObject { ["command"] = $"{command} hook {sub} --agent cursor" });
        return root.ToJsonString(Indented) + "\n";
    }

    public static string? RemoveCursor(string existing) => Remove(existing, "hooks");

    /// <summary>
    /// GitHub Copilot: .github/hooks/turnroi.json. VS Code agent mode reads Claude-style entries (PascalCase events,
    /// "command" + "timeout"); Copilot CLI and cloud agent read the same file (version 1, "timeoutSec").
    /// </summary>
    public static string CopilotFile(string command)
    {
        JsonObject Entry(string sub) => new()
        {
            ["type"] = "command",
            ["command"] = $"{command} hook {sub} --agent copilot",
            ["bash"] = $"{command} hook {sub} --agent copilot",
            ["powershell"] = $"{command} hook {sub} --agent copilot",
            ["timeout"] = 10,
            ["timeoutSec"] = 10,
        };
        var root = new JsonObject
        {
            ["$comment"] = "Generated by TurnROI (turnroi hooks install --agent copilot). Remove with turnroi hooks uninstall --agent copilot.",
            ["version"] = 1,
            ["hooks"] = new JsonObject
            {
                ["PreToolUse"] = new JsonArray(Entry("pre-tool-use")),
                ["PostToolUse"] = new JsonArray(Entry("post-tool-use")),
            },
        };
        return root.ToJsonString(Indented) + "\n";
    }

    private static JsonArray Replace(JsonObject hooks, string evt)
    {
        var list = hooks[evt] as JsonArray ?? new JsonArray();
        hooks[evt] = list;
        foreach (var old in list.Where(IsOurs).ToList()) list.Remove(old);
        return list;
    }

    private static string? Remove(string existing, string key)
    {
        var root = Parse(existing);
        if (root[key] is not JsonObject hooks) return null;
        var removed = 0;
        foreach (var evt in hooks.Select(kv => kv.Key).ToList())
        {
            if (hooks[evt] is not JsonArray list) continue;
            foreach (var item in list.Where(IsOurs).ToList()) { list.Remove(item); removed++; }
            if (list.Count == 0) hooks.Remove(evt);
        }
        if (removed == 0) return null;
        if (hooks.Count == 0) root.Remove(key);
        return root.ToJsonString(Indented) + "\n";
    }

    private static JsonObject Parse(string? json)
    {
        if (string.IsNullOrWhiteSpace(json)) return new JsonObject();
        try
        {
            return JsonNode.Parse(json, documentOptions: new JsonDocumentOptions { CommentHandling = JsonCommentHandling.Skip, AllowTrailingCommas = true }) as JsonObject
                   ?? throw new InvalidOperationException("is not a JSON object");
        }
        catch (JsonException)
        {
            throw new InvalidOperationException("is not valid JSON; fix it first");
        }
    }
}

