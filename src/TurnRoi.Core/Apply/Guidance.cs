using System.Security.Cryptography;
using System.Text;
using System.Text.RegularExpressions;
using TurnRoi.Core.Analysis;
using TurnRoi.Core.Guardrails;

namespace TurnRoi.Core.Apply;

/// <summary>The coding agents TurnROI can write rules, skills and hooks for.</summary>
public enum TargetAgent
{
    Claude,
    Cursor,
    Copilot,
}

/// <summary>A command the agent runs that floods its context, and a quieter way to run it.</summary>
public sealed record QuietCommand(string Command, string Suggestion, int Runs, long Tokens);

/// <summary>Structural outline of a file the agent keeps re-reading, so it can read only the part it needs.</summary>
public sealed record FileOutline(string Path, int Lines, string ContentHash, IReadOnlyList<(int Line, string Text)> Entries);

/// <summary>
/// Agent-neutral guidance derived from a waste profile: a few always-on rules, the body of a repo skill, and tuned
/// guardrail settings. <see cref="ApplyPlanner"/> turns it into each agent's own files.
/// </summary>
public sealed record RepoGuidance(
    string RepoName,
    IReadOnlyList<string> Rules,
    IReadOnlyList<QuietCommand> QuietCommands,
    IReadOnlyList<FileOutline> Outlines,
    string? TestCommand,
    string? Commit,
    GuardrailConfig Guardrails)
{
    public const string SkillName = "repo-efficiency";

    public bool HasSkillContent => QuietCommands.Count > 0 || Outlines.Count > 0 || TestCommand is not null;

    /// <summary>One sentence the agent sees up front; decides when the skill gets loaded.</summary>
    public string SkillDescription
    {
        get
        {
            var parts = new List<string>();
            if (QuietCommands.Count > 0 || TestCommand is not null) parts.Add("running tests, builds or other noisy commands");
            if (Outlines.Count > 0) parts.Add($"before reading {string.Join(", ", Outlines.Take(3).Select(o => Path.GetFileName(o.Path)))}");
            var when = parts.Count == 0 ? "working in this repository" : string.Join(", or ", parts);
            return $"How to work in {RepoName} without wasting tokens: quiet ways to run commands and outlines of large, often-read files. Use when {when}.";
        }
    }

    public string SkillMarkdown()
    {
        var sb = new StringBuilder();
        sb.AppendLine("---");
        sb.AppendLine($"name: {SkillName}");
        // Quoted: the description contains colons, which would break plain YAML.
        sb.AppendLine($"description: \"{SkillDescription.Replace("\\", "\\\\").Replace("\"", "\\\"")}\"");
        sb.AppendLine("---");
        sb.AppendLine();
        sb.AppendLine($"# Working efficiently in {RepoName}");
        sb.AppendLine();
        sb.AppendLine("Generated by TurnROI from this repository's agent sessions. Regenerate with `turnroi profile --apply`.");
        sb.AppendLine();

        if (TestCommand is not null || QuietCommands.Count > 0)
        {
            sb.AppendLine("## Running commands");
            sb.AppendLine();
            sb.AppendLine("Command output stays in context for every later step, so keep it short. Show full logs only when something fails.");
            sb.AppendLine();
            if (TestCommand is not null && QuietCommands.All(q => q.Command != TestCommand))
                sb.AppendLine($"- Tests: `{Quiet.For(TestCommand)}`");
            foreach (var q in QuietCommands)
                sb.AppendLine($"- Instead of `{q.Command}`: `{q.Suggestion}` (past runs averaged ~{q.Tokens / Math.Max(1, q.Runs):N0} tokens of output)");
            sb.AppendLine("- If a quiet run fails, rerun only the failing test or project with full output.");
            sb.AppendLine();
        }

        if (Outlines.Count > 0)
        {
            sb.AppendLine("## Large files you keep re-reading");
            sb.AppendLine();
            sb.AppendLine("Read only the range you need (offset/limit or line ranges). Line numbers are from" +
                          (Commit is null ? " the time this was generated" : $" commit `{Commit}`") +
                          "; if the file changed since, search for the symbol instead of trusting the number.");
            sb.AppendLine();
            foreach (var o in Outlines)
            {
                sb.AppendLine($"### `{o.Path}` ({o.Lines} lines)");
                sb.AppendLine();
                foreach (var (line, text) in o.Entries) sb.AppendLine($"- L{line}: `{text}`");
                sb.AppendLine();
            }
        }

        return sb.ToString().TrimEnd() + Environment.NewLine;
    }

    /// <summary>The always-on rules as Markdown bullets, plus a pointer to the skill.</summary>
    public string RulesMarkdown()
    {
        var sb = new StringBuilder();
        sb.AppendLine("## Token efficiency (managed by TurnROI)");
        sb.AppendLine();
        foreach (var r in Rules) sb.AppendLine($"- {r}");
        if (HasSkillContent)
            sb.AppendLine($"- For quiet commands and outlines of large files, use the `{SkillName}` skill.");
        return sb.ToString().TrimEnd() + Environment.NewLine;
    }

    public static RepoGuidance Build(WasteProfile profile, string repoDir, Func<string, string?>? readFile = null, string? commit = null)
    {
        readFile ??= p => File.Exists(p) ? File.ReadAllText(p) : null;
        var repoName = Path.GetFileName(Path.TrimEndingDirectorySeparator(Path.GetFullPath(repoDir)));

        var quiet = profile.NoisyCommands
            .Where(c => c.Tokens >= 10_000)
            .Take(5)
            .Select(c => new QuietCommand(c.Command, Quiet.For(c.Command), c.Runs, c.Tokens))
            .ToList();

        var outlines = profile.RepeatedFiles
            .Where(f => f.Sessions >= 2 || f.Tokens >= 2_000)
            .Select(f => (f, rel: Relative(repoDir, f.File)))
            .Where(x => x.rel is not null)
            .Select(x => Outline.Of(x.rel!, readFile(Path.Combine(repoDir, x.rel!))))
            .OfType<FileOutline>()
            .Take(5)
            .ToList();

        var rules = new List<string>();
        foreach (var q in quiet.Take(3))
            rules.Add($"Run `{q.Command}` quietly (`{q.Suggestion}`); show full output only for failures.");
        if (profile.RepeatedFiles.Count > 0)
            rules.Add("Don't re-read a file you already have in context and haven't changed; read a specific range if you need more.");
        if (profile.Share(TurnOutcome.Failing) >= 0.10 || profile.Share(TurnOutcome.Unverified) >= 0.30)
            rules.Add($"Before finishing a turn that changes code, run {(profile.CommonTestCommand is { } t ? $"`{Quiet.For(t)}`" : "the relevant tests")} and fix failures.");
        if (profile.Share(TurnOutcome.Wasted) >= 0.15)
            rules.Add("For multi-file or ambiguous changes, propose a short plan and confirm it before editing.");

        var guardrails = new GuardrailConfig();
        if (profile.Turns >= 10)
        {
            // Four times a typical (median) turn: warns on runaway turns, not on normal work.
            guardrails.TurnBudgetTokens = RoundUp(Math.Max(1_000_000, profile.MedianTurnTokens * 4));
        }

        return new RepoGuidance(repoName, rules, quiet, outlines, profile.CommonTestCommand, commit, guardrails);
    }

    private static long RoundUp(long n)
    {
        var step = n >= 10_000_000 ? 1_000_000L : 500_000L;
        return (n + step - 1) / step * step;
    }

    private static string? Relative(string repoDir, string file)
    {
        try
        {
            // GetFullPath(path, basePath) requires a fully qualified base, which "/repo" is not on Windows.
            var root = Path.GetFullPath(repoDir);
            var full = Path.GetFullPath(Path.Combine(root, file));
            var rel = Path.GetRelativePath(root, full);
            return rel.StartsWith("..", StringComparison.Ordinal) || Path.IsPathRooted(rel) ? null : rel.Replace('\\', '/');
        }
        catch (Exception ex) when (ex is ArgumentException or NotSupportedException)
        {
            return null;
        }
    }
}

/// <summary>Quieter invocations of common noisy commands.</summary>
public static class Quiet
{
    private static readonly (Regex Match, Func<string, string> Quiet)[] Known =
    [
        (new(@"^dotnet test\b"), _ => "dotnet test --nologo -v q"),
        (new(@"^dotnet build\b"), _ => "dotnet build --nologo -v q -clp:ErrorsOnly"),
        (new(@"^dotnet restore\b"), _ => "dotnet restore -v q"),
        (new(@"^npm (ci|install)\b"), _ => "npm ci --silent --no-audit --no-fund"),
        (new(@"^npm (run )?test\b"), _ => "npm test --silent"),
        (new(@"^npm run\b"), c => "npm run --silent" + c["npm run".Length..]),
        (new(@"^(yarn|pnpm) (install|i)\b"), c => $"{c.Split(' ')[0]} install --silent"),
        (new(@"^(npx )?jest\b"), _ => "npx jest --silent"),
        (new(@"^(npx )?vitest\b"), _ => "npx vitest run --reporter=dot"),
        (new(@"^(python3? -m )?pytest\b"), _ => "pytest -q --no-header -rf"),
        (new(@"^pip3? install\b"), c => c + " -q"),
        (new(@"^go (test|build|vet)\b"), c => $"{c} 2>&1 | tail -n 40"),
        (new(@"^cargo (test|build|check)\b"), c => c.Replace("cargo ", "cargo -q ", StringComparison.Ordinal)),
        (new(@"^mvn\b"), c => c.Replace("mvn", "mvn -q", StringComparison.Ordinal)),
        (new(@"^(\./)?gradlew?\b"), c => c + " -q"),
        (new(@"^git log\b"), _ => "git log --oneline -n 20"),
        (new(@"^git diff\b"), _ => "git diff --stat, then diff single files"),
        (new(@"^docker build\b"), c => c.Replace("docker build", "docker build -q", StringComparison.Ordinal)),
    ];

    /// <summary>A quieter way to run <paramref name="command"/> (first words of the original), or a tail fallback.</summary>
    public static string For(string command)
    {
        var c = command.Trim();
        foreach (var (match, quiet) in Known)
            if (match.IsMatch(c)) return quiet(c);
        return $"{c} 2>&1 | tail -n 40";
    }
}

/// <summary>Extracts a lightweight structural outline (types, functions, headings) with line numbers.</summary>
public static class Outline
{
    private static readonly Regex CodeDecl = new(
        @"^\s*(?:(?:export|public|internal|private|protected|static|sealed|abstract|partial|async|override|virtual|readonly|final|pub(?:\(crate\))?|default)\s+)*" +
        @"(?:class|interface|record|struct|enum|trait|impl|def|func|fn|function|type|module|namespace|object)\b.*|" +
        @"^\s*(?:public|internal|protected|export)\s+(?:static\s+|async\s+|override\s+|virtual\s+)*[\w<>\[\],.? ]+\s+\w+\s*\(.*",
        RegexOptions.Compiled);

    private static readonly Regex Heading = new(@"^#{1,3}\s+\S", RegexOptions.Compiled);

    public const int MaxEntries = 40;

    public static FileOutline? Of(string relativePath, string? content)
    {
        if (content is null) return null;
        var lines = content.Split('\n');
        var isMarkdown = relativePath.EndsWith(".md", StringComparison.OrdinalIgnoreCase);
        var entries = new List<(int, string)>();

        for (var i = 0; i < lines.Length && entries.Count < MaxEntries; i++)
        {
            var line = lines[i].TrimEnd('\r');
            var hit = isMarkdown ? Heading.IsMatch(line) : CodeDecl.IsMatch(line) && !line.TrimStart().StartsWith("//", StringComparison.Ordinal);
            if (!hit) continue;
            var text = line.Trim().TrimEnd('{').Trim();
            if (text.Length > 110) text = text[..109] + "…";
            entries.Add((i + 1, text));
        }

        var hash = Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(content)))[..8].ToLowerInvariant();
        return new FileOutline(relativePath, lines.Length, hash, entries);
    }
}
